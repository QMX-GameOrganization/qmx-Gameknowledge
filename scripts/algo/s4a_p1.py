def c402_delete():
    f = Fig("c4-02-bst-delete", "删除节点的三种情况", "按被删节点有几个孩子分类处理。", 640,
            "两个孩子时，用右子树的最小值（中序后继）顶替，再删掉那个最小值。")
    x = [180, 500, 820]
    heads = ["① 叶子：直接删", "② 一个孩子：孩子顶上去", "③ 两个孩子：用后继顶替"]
    for i, h in enumerate(heads):
        f.rect(x[i] - 150, 100, 300, 470, ["blue", "green", "orange"][i])
        f.text(x[i], 132, h, 18, PALETTE[["blue", "green", "orange"][i]][1], "700", "middle")
    # ① 删 4
    tree(f, {6: (x[0], 190), 4: (x[0] - 60, 270), 7: (x[0] + 60, 270)}, [(6, 4), (6, 7)], {4: "red"})
    f.text(x[0], 315, "删 4", 15, SUB, anchor="middle")
    tree(f, {6: (x[0], 390), 7: (x[0] + 60, 470)}, [(6, 7)])
    # ② 删 14
    tree(f, {10: (x[1], 190), 14: (x[1] + 60, 270), 13: (x[1], 350)}, [(10, 14), (14, 13)], {14: "red"})
    f.text(x[1] + 100, 275, "删 14", 15, SUB, anchor="start")
    tree(f, {10: (x[1], 440), 13: (x[1] + 60, 510)}, [(10, 13)])
    # ③ 删 3
    p3 = {3: (x[2], 180), 1: (x[2] - 70, 250), 6: (x[2] + 60, 250), 4: (x[2], 320), 7: (x[2] + 120, 320)}
    tree(f, p3, [(3, 1), (3, 6), (6, 4), (6, 7)], {3: "red", 4: "green"})
    f.text(x[2] - 125, 330, "后继 = 4", 15, PALETTE["green"][1], "700")
    q3 = {4: (x[2], 400), 1: (x[2] - 70, 470), 6: (x[2] + 60, 470), 7: (x[2] + 120, 530)}
    tree(f, q3, [(4, 1), (4, 6), (6, 7)], {4: "green"})
    f.arrow(x[0], 335, x[0], 365, GREY)
    f.arrow(x[1] + 100, 330, x[1] + 100, 400, GREY)
    f.arrow(x[2], 350, x[2], 372, GREY)
    return f.save()


def c402_degenerate():
    f = Fig("c4-02-degenerate", "插入顺序决定树形", "同样 5 个数，有序插入退化成链，查找变成 O(n)。", 520,
            "平衡树（4.9 的 AVL、红黑树）在插入删除后自动调整，保证树高约 log n。")
    f.rect(32, 100, 450, 380, "red")
    f.text(48, 132, "按 1 2 3 4 5 顺序插入", 18, PALETTE["red"][1], "700")
    pos = {i + 1: (150 + i * 55, 190 + i * 56) for i in range(5)}
    tree(f, pos, [(i, i + 1) for i in range(1, 5)])
    f.text(48, 460, "树高 5，查找 5 要比较 5 次。", 17)
    f.rect(518, 100, 450, 380, "green")
    f.text(534, 132, "按 3 2 4 1 5 顺序插入", 18, PALETTE["green"][1], "700")
    pos = {3: (743, 190), 2: (653, 280), 4: (833, 280), 1: (608, 370), 5: (878, 370)}
    tree(f, pos, [(3, 2), (3, 4), (2, 1), (4, 5)], {3: "green", 2: "green", 4: "green", 1: "green", 5: "green"})
    f.text(534, 460, "树高 3，查找最多比较 3 次。", 17)
    return f.save()


def build_all():
    w = []
    for fn in (c401_traversal, c401_iter, c401_rebuild, c402_search, c402_delete, c402_degenerate):
        w += fn()
