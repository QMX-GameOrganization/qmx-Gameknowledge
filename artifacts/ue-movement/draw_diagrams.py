out=Path('public/assets/ue-movement'); out.mkdir(parents=True,exist_ok=True)
def canvas(title,subtitle,h=660):
    return [f'<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="{h}" viewBox="0 0 1120 {h}" role="img" aria-labelledby="title desc"><title id="title">{escape(title)}</title><desc id="desc">{escape(subtitle)}</desc><defs><marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" orient="auto"><path d="M0,0 L0,6 L9,3 z" fill="#536d88"/></marker></defs><rect width="1120" height="{h}" rx="18" fill="#f4f7fc"/><g font-family="Microsoft YaHei, Noto Sans CJK SC, sans-serif" fill="#16314d"><text x="42" y="54" font-size="28" font-weight="700">{escape(title)}</text><text x="42" y="88" font-size="17" fill="#4f657c">{escape(subtitle)}</text>']
def box(s,x,y,w,h,title,lines=(),color='#e1edff'):
    s.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="{color}" stroke="#b9cbdf"/><text x="{x+20}" y="{y+34}" font-size="21" font-weight="700">{escape(title)}</text>')
    for i,t in enumerate(lines): s.append(f'<text x="{x+20}" y="{y+65+i*27}" font-size="17">{escape(t)}</text>')
def arrow(s,x,y,xx,yy,label=''):
    s.append(f'<path d="M{x},{y} L{xx},{yy}" stroke="#536d88" stroke-width="2" fill="none" marker-end="url(#arrow)"/>')
    if label:s.append(f'<text x="{(x+xx)/2+10}" y="{(y+yy)/2-8}" font-size="16">{escape(label)}</text>')
def save(name,s): (out/name).write_text(''.join(s)+ '</g></svg>',encoding='utf-8')
